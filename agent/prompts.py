def meme_catalog_lines(limit: int = 0) -> list[str]:
    """当前可用表情包的目录行（``名字：描述``）；没启用或无数据时返回空列表。"""
    try:
        from messaging.meme import get_library, is_enabled

        if not is_enabled():
            return []
        return get_library().catalog(limit)
    except Exception:  # noqa: BLE001 - 表情包坏了不能连累提示词
        return []


def _project_root(settings=None):
    root = getattr(getattr(settings, "paths", None), "root", None)
    if root:
        return Path(root)
    return Path(__file__).resolve().parent.parent


def _read_prompt_file(value: str, settings=None) -> str:
    """读取人设 / 通用行为 Markdown；相对路径按项目根目录解析。"""
    text = str(value or "").strip()
    if not text:
        return ""
    path = Path(text)
    if not path.is_absolute():
        path = _project_root(settings) / path
    try:
        return path.read_text(encoding="utf-8").strip()
    except OSError:
        return ""


def _persona_paths(settings=None) -> tuple[str, str]:
    """配置里选择人设文件；没配就用 ``agent/personas`` 下的默认文件。"""
    section = {}
    if settings is not None:
        try:
            section = settings.section("agent") or {}
        except Exception:  # noqa: BLE001 - 旧配置可能没有 agent 段
            section = {}
    persona = str(section.get("persona_file") or "").strip() or PERSONA_FILE_DEFAULT
    core = (
        str(section.get("persona_core_file") or "").strip()
        or PERSONA_CORE_FILE_DEFAULT
    )
    return persona, core


def build_persona_parts(settings=None) -> tuple[str, str]:
    """返回 ``(角色卡, 通用群聊行为)``；文件缺失或为空时用内置兜底。"""
    persona_file, core_file = _persona_paths(settings)
    persona = _read_prompt_file(persona_file, settings) or FALLBACK_PERSONA
    core = _read_prompt_file(core_file, settings) or FALLBACK_CORE
    return persona, core


def build_system_prompt(limit: int = 0, settings=None) -> str:
    """把角色卡、通用行为和表情包目录填进 SYSTEM_PROMPT。

    ``limit<=0`` 表示表情包全给。人设文件路径来自
    ``agent.persona_file`` / ``agent.persona_core_file``，改文件不需要重启代码，
    但本进程内只在 Agent 初始化时读一次（与旧版一致）。
    """
    persona, core = build_persona_parts(settings)
    lines = meme_catalog_lines(limit)
    block = (
        "\n".join(f"- {line}" for line in lines)
        if lines
        else "（现在没有可用的表情包，这一轮不要写 <meme>）"
    )
    return (
        SYSTEM_PROMPT.replace(_PERSONA_SLOT, persona)
        .replace(_CORE_SLOT, core)
        .replace(_MEME_SLOT, block)
    )

